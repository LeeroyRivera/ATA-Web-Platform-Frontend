/**
 * Data layer used by the screens. Today every function returns sample data after a short
 * delay; when the .NET API exists, these bodies become `fetch('/api/...')` calls and the
 * screens stay the same.
 */
import JSZip from 'jszip'
import { RECENT_UPLOADS, SAMPLE_INVOICES } from './mock/data.ts'
import type { GrpoResult, Invoice, UploadBatch, User } from './types.ts'

export type { GrpoResult, Invoice, UploadBatch, User } from './types.ts'

const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms))

export const ACCEPTED_EXTENSIONS = ['.xlsx', '.xlsm']
export const MAX_FILE_SIZE_MB = 20

function nameFromUsername(username: string): string {
  return username
    .split(/[.\s_-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join(' ')
}

export function userFromUsername(username: string): User {
  const clean = username.trim().replace(/@.*$/, '')
  const name = nameFromUsername(clean) || clean
  const parts = name.split(' ')
  const initials = (
    (parts[0]?.[0] ?? '') + (parts.length > 1 ? (parts.at(-1)?.[0] ?? '') : '')
  ).toUpperCase()
  return { username: clean, name, initials: initials || '?' }
}

/** Simulated sign-in: any username and password are accepted. */
export async function login(username: string, _password: string): Promise<User> {
  await delay(1000)
  return userFromUsername(username)
}

export async function getRecentUploads(): Promise<UploadBatch[]> {
  await delay(600)
  return RECENT_UPLOADS
}

/** Simulated processing of the GRPO Excel: always returns the sample invoices. */
export async function processGrpoFile(file: File): Promise<GrpoResult> {
  await delay(1500)
  return { fileName: file.name, invoices: SAMPLE_INVOICES }
}

// ---- Sample downloads (CSV opens in Excel). Replaced by the real .xlsx from the API later.

function invoiceCsv(invoice: Invoice): string {
  const rows = [
    ['Commercial Invoice', invoice.invoiceNumber],
    ['Container', invoice.container],
    ['GRPO #', invoice.grpoNumber],
    ['Quantity', String(invoice.quantity)],
    ['Amount (USD)', invoice.amountUsd.toFixed(2)],
    [],
    ['Sample file generated by the ATA Web Platform UI mockup'],
  ]
  return rows.map((row) => row.join(',')).join('\r\n')
}

function saveBlob(blob: Blob, fileName: string) {
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = fileName
  document.body.appendChild(link)
  link.click()
  link.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export async function downloadInvoice(invoice: Invoice): Promise<void> {
  await delay(400)
  const blob = new Blob([invoiceCsv(invoice)], { type: 'text/csv;charset=utf-8' })
  saveBlob(blob, `${invoice.invoiceNumber}_${invoice.container}.csv`)
}

export async function downloadAllInvoices(result: GrpoResult): Promise<void> {
  const zip = new JSZip()
  for (const invoice of result.invoices) {
    zip.file(`${invoice.invoiceNumber}_${invoice.container}.csv`, invoiceCsv(invoice))
  }
  const [blob] = await Promise.all([zip.generateAsync({ type: 'blob' }), delay(800)])
  const base = result.fileName.replace(/\.[^.]+$/, '')
  saveBlob(blob, `${base}_invoices.zip`)
}
